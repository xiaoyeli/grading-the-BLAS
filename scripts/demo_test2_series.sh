#!/bin/bash

REPO_ROOT=$(git rev-parse --show-toplevel)
cd ${REPO_ROOT}

DGEMM_IMPLEMENTATIONS=(
    NAIVE_TRIPLE_LOOP_EXTENDED_PRECISION
    NAIVE_TRIPLE_LOOP_FP64
    OZIMMU
    OZIMMU_ADDB_SCALING
    GEMMUL8_ACCU
    GEMMUL8_ACCU_ADDB_SCALING
    GEMMUL8_FAST
    GEMMUL8_FAST_ADDB_SCALING
    STRASSEN
    STRASSEN_ADDB_SCALING
)

for impl in "${DGEMM_IMPLEMENTATIONS[@]}"
do
    echo "================== Testing ${impl}"
    make run MIN_DIM=32 MAX_DIM=1024 SCALING_FACTOR=1000 DGEMM_IMPL=${impl} INPUT_TYPE=test2a
    make run MIN_DIM=32 MAX_DIM=1024 SCALING_FACTOR=500 DGEMM_IMPL=${impl} INPUT_TYPE=test2b
    make run MIN_DIM=32 MAX_DIM=1024 SCALING_FACTOR=500 DGEMM_IMPL=${impl} INPUT_TYPE=test2c
done