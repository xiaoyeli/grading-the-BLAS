#!/bin/bash

REPO_ROOT=$(git rev-parse --show-toplevel)
cd ${REPO_ROOT}

DGEMM_IMPLEMENTATION=$1

echo "================== Testing ${DGEMM_IMPLEMENTATION}"
for SCALING_FACTOR in 0 100 200 300 400 500
do
    make run MIN_DIM=32 MAX_DIM=1024 SCALING_FACTOR=${SCALING_FACTOR} DGEMM_IMPL=${DGEMM_IMPLEMENTATION} INPUT_TYPE=test2c
done